export const getSubRegionsByRegion = (regionId) =>
  SUB_REGIONS.filter((sr) => sr.regionId === regionId);

export const getDistrictsBySubRegion = (subRegionId) =>
  DISTRICTS.filter((d) => d.subRegionId === subRegionId);

export const getDistrictsByRegion = (regionId) => {
  const srIds = SUB_REGIONS
    .filter((sr) => sr.regionId === regionId)
    .map((sr) => sr.id);
  return DISTRICTS.filter((d) => srIds.includes(d.subRegionId));
};

export const getRegionName = (regionId) =>
  REGIONS.find((r) => r.id === regionId)?.name || "";

export const getSubRegionName = (subRegionId) =>
  SUB_REGIONS.find((sr) => sr.id === subRegionId)?.name || "";
